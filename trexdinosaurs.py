import math
import pandas as pd

COMBINE_FILE = "combine_results.csv"
PLAYERS_FILE = "players.csv"
CAREER_FILE = "player_career_successes.csv"

combine = pd.read_csv(COMBINE_FILE, na_values=["NA", ""])
players = pd.read_csv(PLAYERS_FILE, na_values=["NA", ""])
career = pd.read_csv(CAREER_FILE, na_values=["NA", ""])

for df in (combine, players, career):
    if "nfl_id" in df.columns:
        df["nfl_id"] = pd.to_numeric(df["nfl_id"], errors="coerce")

combine["draft_year"] = pd.to_numeric(combine["draft_year"], errors="coerce")
combine["arm_length"] = pd.to_numeric(combine["arm_length"], errors="coerce")

career_metrics = [
    "career_defensive_snaps",
    "career_games_active",
    "career_games_started",
    "ap_all_pro_1st_team",
    "ap_all_pro_2nd_team",
    "pro_bowl_original_ballot",
]

for column in career_metrics:
    if column in career.columns:
        career[column] = pd.to_numeric(career[column], errors="coerce")

dl = combine.loc[
    combine["combine_position"].astype(str).str.upper().eq("DL")
    & combine["arm_length"].notna()
].copy()

if len(dl) < 10:
    raise ValueError("Too few DLs with arm-length data for 10% groups.")

group_size = max(1, math.ceil(len(dl) * 0.10))

dl = dl.sort_values(
    ["arm_length", "nfl_id"]
).reset_index(drop=True)

dl["arm_group"] = "Middle 80%"
dl.loc[:group_size - 1, "arm_group"] = "T-Rex"
dl.loc[len(dl) - group_size:, "arm_group"] = "Pterodactyl"

print(f"DLs with arm-length data: {len(dl)}")
print(f"T-Rexes: {group_size}")
print(f"Pterodactyls: {group_size}")
print(f"Middle-80% controls: {len(dl) - 2 * group_size}")

name_columns = [
    column for column in ["nfl_id", "display_name", "nfl_position"]
    if column in players.columns
]

dl = dl.merge(
    players[name_columns].drop_duplicates("nfl_id"),
    on="nfl_id",
    how="left",
)

dl = dl.merge(
    career[["nfl_id"] + [c for c in career_metrics if c in career.columns]]
        .drop_duplicates("nfl_id"),
    on="nfl_id",
    how="left",
)

combine_metrics = [
    "arm_length",
    "combine_height",
    "combine_weight",
    "hand_size",
    "wing_span",
    "ten_yd_split",
    "forty",
    "vertical",
    "broad_jump",
    "three_cone",
    "short_shuttle",
    "bench_reps",
    "ngs_athleticism_score",
    "ngs_college_production_score",
    "ngs_final_score",
]
combine_metrics = [c for c in combine_metrics if c in dl.columns]

available_career_metrics = [
    c for c in career_metrics if c in dl.columns
]

summary_rows = []

for group in ["T-Rex", "Middle 80%", "Pterodactyl"]:
    group_data = dl.loc[dl["arm_group"] == group]

    for metric in combine_metrics + available_career_metrics:
        values = group_data[metric].dropna()

        summary_rows.append({
            "arm_group": group,
            "metric": metric,
            "players_with_result": len(values),
            "average": values.mean(),
            "median": values.median(),
        })

summary = pd.DataFrame(summary_rows)

print("\nAverage Combine measurements and scores")
print("---------------------------------------")
print(
    summary.loc[summary["metric"].isin(combine_metrics)]
    .round(2)
    .to_string(index=False)
)

print("\nAverage career outcomes")
print("-----------------------")
print(
    summary.loc[summary["metric"].isin(available_career_metrics)]
    .round(2)
    .to_string(index=False)
)

for metric in available_career_metrics:
    dl[f"{metric}_within_year_percentile"] = (
        dl.groupby("draft_year")[metric].rank(pct=True)
    )

percentile_metrics = [
    f"{metric}_within_year_percentile"
    for metric in available_career_metrics
]

year_adjusted_rows = []

for group in ["T-Rex", "Middle 80%", "Pterodactyl"]:
    group_data = dl.loc[dl["arm_group"] == group]

    for metric in percentile_metrics:
        values = group_data[metric].dropna()

        year_adjusted_rows.append({
            "arm_group": group,
            "career_metric_percentile": metric,
            "players_with_result": len(values),
            "average_within_year_percentile": values.mean(),
        })

year_adjusted = pd.DataFrame(year_adjusted_rows)

print("\nCareer outcomes ranked within each draft year")
print("----------------------------------------------")
print(year_adjusted.round(3).to_string(index=False))

print("\nPlayers by arm-length group")
print("---------------------------")
for group in ["T-Rex", "Middle 80%", "Pterodactyl"]:
    columns = [
        c for c in [
            "display_name",
            "draft_year",
            "nfl_position",
            "arm_length",
            "career_defensive_snaps",
            "career_games_started",
        ]
        if c in dl.columns
    ]

    print(f"\n{group}")
    print(dl.loc[dl["arm_group"] == group, columns].to_string(index=False))

bain_arm_length = 30.875
trex_max = dl.loc[dl["arm_group"] == "T-Rex", "arm_length"].max()
pterodactyl_min = dl.loc[
    dl["arm_group"] == "Pterodactyl", "arm_length"
].min()

if bain_arm_length <= trex_max:
    bain_group = "T-Rex"
elif bain_arm_length >= pterodactyl_min:
    bain_group = "Pterodactyl"
else:
    bain_group = "Middle 80%"

print(
    f"\nReuben Bain Jr. at {bain_arm_length:.3f} inches "
    f"would be classified as: {bain_group}"
)

dl.to_csv("dl_arm_groups_with_career_outcomes.csv", index=False)
summary.to_csv("dl_arm_group_averages.csv", index=False)
year_adjusted.to_csv("dl_arm_group_within_year_ranks.csv", index=False)

print("\nSaved:")
print("  dl_arm_groups_with_career_outcomes.csv")
print("  dl_arm_group_averages.csv")
print("  dl_arm_group_within_year_ranks.csv")

import pandas as pd
import matplotlib.pyplot as plt

data = pd.read_csv("dl_arm_groups_with_career_outcomes.csv")

groups = ["T-Rex", "Middle 80%", "Pterodactyl"]
colors = {
    "T-Rex": "#d95f02",
    "Middle 80%": "#7570b3",
    "Pterodactyl": "#1b9e77",
}

scores = [
    ("ngs_athleticism_score", "NGS Athleticism Score"),
    ("ngs_college_production_score", "NGS College Production Score"),
    ("ngs_final_score", "NGS Final Score"),
]


def plot_score(data, column, title, filename):
    """Plot the score distribution and mean for each arm-length group."""
    data[column] = pd.to_numeric(data[column], errors="coerce")

    group_values = [
        data.loc[data["arm_group"] == group, column].dropna()
        for group in groups
    ]

    fig, ax = plt.subplots(figsize=(8, 5))

    box = ax.boxplot(
        group_values,
        labels=groups,
        patch_artist=True,
        showmeans=True,
        meanprops={
            "marker": "D",
            "markerfacecolor": "black",
            "markeredgecolor": "black",
            "markersize": 6,
        },
    )

    for patch, group in zip(box["boxes"], groups):
        patch.set_facecolor(colors[group])
        patch.set_alpha(0.55)

    for position, (group, values) in enumerate(zip(groups, group_values), start=1):
        if len(values) > 0:
            x_positions = [
                position + ((i % 5) - 2) * 0.045
                for i in range(len(values))
            ]
            ax.scatter(
                x_positions,
                values,
                color=colors[group],
                alpha=0.7,
                s=24,
                zorder=3,
            )

            ax.text(
                position,
                ax.get_ylim()[0],
                f"n={len(values)}",
                ha="center",
                va="bottom",
                fontsize=9,
            )

    for position, (group, values) in enumerate(zip(groups, group_values), start=1):
        if len(values) > 0:
            ax.annotate(
                f"mean={values.mean():.1f}",
                xy=(position, values.mean()),
                xytext=(0, 9),
                textcoords="offset points",
                ha="center",
                fontsize=9,
                fontweight="bold",
            )

    ax.set_title(title)
    ax.set_ylabel("Score")
    ax.set_xlabel("Arm-length group")
    ax.grid(axis="y", alpha=0.25)

    fig.tight_layout()
    fig.savefig(filename, dpi=200, bbox_inches="tight")
    plt.show()

    print(f"Saved {filename}")


for column, title in scores:
    if column not in data.columns:
        print(f"Skipping {title}: column '{column}' not found.")
        continue

    plot_score(
        data=data,
        column=column,
        title=title + " by DL Arm-Length Group",
        filename=column + "_by_arm_group.png",
    )

import pandas as pd
import matplotlib.pyplot as plt
import numpy as np

data = pd.read_csv("dl_arm_groups_with_career_outcomes.csv")

group_order = ["T-Rex", "Middle 80%", "Pterodactyl"]
data = data.loc[data["arm_group"].isin(group_order)].copy()

outcomes = [
    "career_defensive_snaps",
    "career_games_active",
    "career_games_started",
]

for column in outcomes:
    data[column] = pd.to_numeric(data[column], errors="coerce")

group_counts = (
    data.groupby("arm_group")["nfl_id"]
    .nunique()
    .reindex(group_order)
    .fillna(0)
    .astype(int)
)

total_snaps = (
    data.groupby("arm_group")["career_defensive_snaps"]
    .sum()
    .reindex(group_order)
)

fig, ax = plt.subplots(figsize=(8, 5))
bars = ax.bar(group_order, total_snaps.values, color=["#d95f02", "#7570b3", "#1b9e77"])

ax.set_title("Total career defensive snaps by arm-length group")
ax.set_ylabel("Total defensive snaps")
ax.set_xlabel("Arm-length group")
ax.bar_label(bars, labels=[f"{int(v):,}" for v in total_snaps.values], padding=3)

for i, group in enumerate(group_order):
    ax.text(
        i,
        total_snaps.iloc[i] * 0.92 if total_snaps.iloc[i] else 0,
        f"n={group_counts[group]}",
        ha="center",
        va="top",
        color="white",
        fontweight="bold",
    )

ax.text(
    0.01,
    -0.22,
    "Totals are strongly affected by group size; the middle group has many more players.",
    transform=ax.transAxes,
    fontsize=9,
)
fig.tight_layout()
fig.savefig("graph1_total_defensive_snaps.png", dpi=200, bbox_inches="tight")

snap_summary = (
    data.groupby("arm_group")["career_defensive_snaps"]
    .agg(["mean", "median"])
    .reindex(group_order)
)

x = np.arange(len(group_order))
width = 0.36

fig, ax = plt.subplots(figsize=(8, 5))
mean_bars = ax.bar(
    x - width / 2,
    snap_summary["mean"],
    width,
    label="Mean per player",
    color="#4c78a8",
)
median_bars = ax.bar(
    x + width / 2,
    snap_summary["median"],
    width,
    label="Median per player",
    color="#f58518",
)

ax.set_title("Career defensive snaps per player")
ax.set_ylabel("Defensive snaps")
ax.set_xticks(x, group_order)
ax.legend()

ax.bar_label(mean_bars, fmt="%.0f", padding=3)
ax.bar_label(median_bars, fmt="%.0f", padding=3)

for i, group in enumerate(group_order):
    ax.text(
        i,
        -0.16,
        f"n={group_counts[group]}",
        ha="center",
        va="top",
        transform=ax.get_xaxis_transform(),
        fontsize=9,
    )

fig.tight_layout()
fig.savefig("graph2_snaps_per_player.png", dpi=200, bbox_inches="tight")

percentile_columns = []

for outcome in outcomes:
    percentile_col = f"{outcome}_year_percentile"

    data[percentile_col] = data.groupby("draft_year")[outcome].rank(
        pct=True,
        method="average",
    )

    percentile_columns.append(percentile_col)

percentile_summary = (
    data.groupby("arm_group")[percentile_columns]
    .mean()
    .reindex(group_order)
)

percentile_summary.columns = [
    "Defensive snaps",
    "Games active",
    "Games started",
]

fig, ax = plt.subplots(figsize=(9, 5.5))
percentile_summary.plot(
    kind="bar",
    ax=ax,
    color=["#4c78a8", "#f58518", "#54a24b"],
)

ax.axhline(
    0.5,
    color="black",
    linestyle="--",
    linewidth=1,
    label="50th percentile",
)
ax.set_title("Average career-outcome percentile within draft year")
ax.set_ylabel("Mean percentile (higher = higher relative rank)")
ax.set_xlabel("Arm-length group")
ax.set_ylim(0, 1)
ax.set_xticklabels(group_order, rotation=0)
ax.legend(title="Outcome", bbox_to_anchor=(1.02, 1), loc="upper left")

fig.tight_layout()
fig.savefig("graph3_year_adjusted_percentiles.png", dpi=200, bbox_inches="tight")

plt.show()

print("Saved graphs:")
print("  graph1_total_defensive_snaps.png")
print("  graph2_snaps_per_player.png")
print("  graph3_year_adjusted_percentiles.png")